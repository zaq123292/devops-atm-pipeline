#!/usr/bin/env bash
# 回滚测试完整演示：
#   1. 部署 v1.0.0（稳定版本）→ 成功
#   2. 部署 v2.0.0（有缺陷版本）→ 健康检查失败
#   3. 自动回滚到 v1.0.0 → 成功
# 用法: ./scripts/rollback_test.sh

set -e

echo ""
echo "╔══════════════════════════════════════════════╗"
echo "║     回滚测试演示 - 自动回滚机制验证          ║"
echo "╚══════════════════════════════════════════════╝"

# 清理之前的状态
rm -f .current_version

# ==============================================
# 步骤 1：部署 v1.0.0 稳定版本
# ==============================================
echo ""
echo "━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━"
echo "【步骤 1】部署 v1.0.0 稳定版本"
echo "━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━"
DOCKERFILE=Dockerfile ./scripts/deploy.sh v1.0.0

echo ""
echo "✅ v1.0.0 部署成功，当前版本: $(cat .current_version)"

# ==============================================
# 步骤 2：部署 v2.0.0 有缺陷版本（模拟故障）
# ==============================================
echo ""
echo "━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━"
echo "【步骤 2】部署 v2.0.0（模拟有缺陷的新版本）"
echo "━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━"
set +e
DOCKERFILE=Dockerfile.broken ./scripts/deploy.sh v2.0.0
DEPLOY_EXIT=$?
set -e

echo ""
echo "📝 v2.0.0 部署退出码: ${DEPLOY_EXIT}（非 0 表示部署失败并已触发回滚）"

# ==============================================
# 步骤 3：验证自动回滚结果
# ==============================================
echo ""
echo "━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━"
echo "【步骤 3】验证自动回滚结果"
echo "━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━"

CURRENT_VERSION=$(cat .current_version)
echo "当前版本: ${CURRENT_VERSION}"

if [ "${CURRENT_VERSION}" == "v1.0.0" ]; then
    echo ""
    echo "╔══════════════════════════════════════════════╗"
    echo "║  ✅ 回滚测试成功！                           ║"
    echo "║  服务已从 v2.0.0 自动回滚到 v1.0.0          ║"
    echo "╚══════════════════════════════════════════════╝"
else
    echo ""
    echo "╔══════════════════════════════════════════════╗"
    echo "║  ❌ 回滚测试失败！                           ║"
    echo "║  当前版本应为 v1.0.0，实际为 ${CURRENT_VERSION}"
    echo "╚══════════════════════════════════════════════╝"
    exit 1
fi

echo ""
echo "最终服务状态:"
curl -s http://localhost/health
echo ""
